const definitions = { line, ...foundationFilms, perspective, light, form, car: coupeChapters };

export function compileFilm(chapterActions, resetEachChapter = false) {
  let cursor = 0;
  const actions = [];
  const chapters = chapterActions.map((entries, chapter) => {
    const start = cursor;
    entries.forEach((entry, index) => {
      actions.push({ ...entry, kind: entry.kind || 'stroke', chapter, start: cursor, end: cursor + entry.duration, id: `${chapter}-${index}` });
      cursor += entry.duration;
    });
    return { start, end: cursor, duration: cursor - start };
  });
  return { chapters, actions, duration: cursor, resetEachChapter };
}

export const films = Object.fromEntries(Object.entries(definitions).map(([id, chapters]) => [id, { ...compileFilm(chapters, id === 'line' || id in foundationFilms), revision: id === 'car' ? 'reference-coupe-v1' : id === 'line' ? 'clear-line-v2' : 'foundations-v1' }]));

export function chapterAt(film, time) {
  return Math.max(0, film.chapters.findLastIndex(chapter => time >= chapter.start));
}

export function actionAt(film, time) {
  return film.actions.find(action => time >= action.start && time < action.end) || film.actions.at(-1);
}

export function strokeProgress(action, time) {
  const lead = Math.min(1.2, action.duration * .15);
  const drawingTime = Math.max(.1, action.duration - lead - Math.min(1.3, action.duration * .15));
  return Math.max(0, Math.min(1, (time - action.start - lead) / drawingTime));
}

export function formatTime(time) {
  const seconds = Math.max(0, Math.floor(time));
  return `${String(Math.floor(seconds / 60)).padStart(2, '0')}:${String(seconds % 60).padStart(2, '0')}`;
}
