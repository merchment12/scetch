const stroke = (d, caption, options = {}) => ({ d, caption, duration: 7, ...options });
const pause = (caption, duration = 8) => ({ caption, duration, kind: 'pause' });
const ghost = (d, caption, options = {}) => stroke(d, caption, { kind: 'ghost', duration: 5, ...options });
const circle = (x, y, r) => `M${x + r} ${y}a${r} ${r} 0 1 0 ${-2 * r} 0a${r} ${r} 0 1 0 ${2 * r} 0`;
const split = d => d.match(/M[^M]+/g) || [d];

function drawGroup(id, group, captions) {
  let index = 0;
  return illustrations[id][group].flatMap(path => split(path.d).map(d => stroke(d, captions[index++] || captions.at(-1), {
    style: path.fill ? 'wash' : path.guide ? 'guide' : path.accent ? 'accent' : path.light ? 'light' : 'ink',
    fill: path.fill, duration: path.fill ? 5 : 7,
  })));
}

